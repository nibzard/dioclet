PRINT = REPO / "print"
A4_SHORT_PT = 595.2756   # 210 mm
A4_LONG_PT = 841.8898    # 297 mm


def image_matrix(page):
    """The transform in force when the page paints its first image."""
    from pypdf.generic import ContentStream

    def mul(m, n):
        a, b, c, d, e, f = m
        A, B, C, D, E, F = n
        return (a * A + b * C, a * B + b * D, c * A + d * C, c * B + d * D,
                e * A + f * C + E, e * B + f * D + F)

    ctm, stack = (1, 0, 0, 1, 0, 0), []
    xobjs = page["/Resources"]["/XObject"]
    for operands, op in ContentStream(page.get_contents(), page.pdf).operations:
        if op == b"q":
            stack.append(ctm)
        elif op == b"Q":
            ctm = stack.pop()
        elif op == b"cm":
            ctm = mul(tuple(float(v) for v in operands), ctm)
        elif op == b"Do" and xobjs[operands[0]].get("/Subtype") == "/Image":
            return ctm
    raise AssertionError("page paints no image")


class LayoutExport(unittest.TestCase):
    """The exported geometry matches the kit's own layout functions."""

    @classmethod
    def setUpClass(cls):
        cls.rules = engine.load_rules(str(REPO / kit.RULES_FILE))
        cls.export = json.loads((ART_BUILD / "layout.json").read_text())

    def test_export_exists_and_pins_the_rules_file(self):
        self.assertEqual(self.export["rules_file"], kit.RULES_FILE)
        self.assertEqual(self.export["rules_hash"], engine.rules_hash(self.rules))

    def test_palace_specials_match_the_kit_positions(self):
        L = kit.build_layout(self.rules)
        export = self.export["palace"]
        ax0, ay0, ax1, ay1 = L["art"]
        for name, cell in L["board"].gates.items():
            x, y = L["pos"](tuple(cell))
            self.assertAlmostEqual(export["gates"][name][0], x - ax0, places=3)
            self.assertAlmostEqual(export["gates"][name][1], ay1 - y, places=3)
        for (_cell, (x, y)), space in zip(L["spaces"], export["spaces"]):
            self.assertAlmostEqual(space["mm"][0], x - ax0, places=3)
            self.assertAlmostEqual(space["mm"][1], ay1 - y, places=3)

    def test_succession_card_spaces_match_the_rules(self):
        S = kit.build_succession_layout(self.rules)
        export = self.export["succession"]
        ax0, ay0, ax1, ay1 = S["art"]
        sites = self.rules["board_level2"]["support_sites"]
        self.assertEqual(len(export["card_spaces"]), len(sites))
        for cell, (ex, ey) in zip(sites, export["card_spaces"]):
            x, y = S["pos"](tuple(cell))
            self.assertAlmostEqual(ex, x - ax0, places=3)
            self.assertAlmostEqual(ey, ay1 - y, places=3)
        self.assertEqual(export["size_mm"], self.export["palace"]["size_mm"])
        self.assertEqual(export["cut_mm"], self.export["palace"]["cut_mm"])

    def test_faction_cards_match_the_kit_list(self):
        exported = [(f["name"], f["badge"]) for f in self.export["cards"]["factions"]]
        self.assertEqual(exported, [(n, b) for n, b, _l1, _l2 in kit.FACTION_CARDS])

    def test_cards_match_the_kit_card_list(self):
        items = self.export["cards"]["items"]
        self.assertEqual([i["name"] for i in items], [c[0] for c in kit.CARDS])
        self.assertEqual(self.export["cards"]["size_mm"], [kit.CARD_W, kit.CARD_H])


@unittest.skipUnless((ART_BUILD / "assets" / "palace-board.png").exists(),
                     "art assets not rendered (run: node art/render.mjs)")
class ArtKitPdfs(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        # Rebuild only the ART PDFs, into a scratch folder: the committed
        # copies in print/ must not change when the tests run. The BW
        # PDFs have their own tests.
        cls.out = Path(tempfile.mkdtemp(prefix="dioclet-art-"))
        rules_arg = str(REPO / kit.RULES_FILE)
        script = (
            "import sys; sys.path.insert(0, '.'); sys.path.insert(0, 'tools');"
            "import make_a4_print_kit as kit;"
            f"rules = kit.engine.load_rules({rules_arg!r});"
            f"kit.art_board_pdf({str(cls.out / 'imperial-rivals-305ad-board-4xA4-ART.pdf')!r}, kit.build_layout(rules));"
            f"kit.art_succession_pdf({str(cls.out / 'imperial-rivals-305ad-succession-map-ART.pdf')!r}, kit.build_succession_layout(rules));"
            f"kit.art_cards_tokens_pdf({str(cls.out / 'imperial-rivals-305ad-cards-tokens-ART.pdf')!r})"
        )
        subprocess.run([sys.executable, "-c", script], cwd=str(REPO), check=True)

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.out, ignore_errors=True)

    def test_board_is_four_landscape_pages(self):
        reader = PdfReader(self.out / "imperial-rivals-305ad-board-4xA4-ART.pdf")
        self.assertEqual(len(reader.pages), 4)
        for page in reader.pages:
            self.assertAlmostEqual(float(page.mediabox.width), A4_LONG_PT, places=1)
            self.assertAlmostEqual(float(page.mediabox.height), A4_SHORT_PT, places=1)

    def test_every_art_board_page_carries_an_image(self):
        reader = PdfReader(self.out / "imperial-rivals-305ad-board-4xA4-ART.pdf")
        for page in reader.pages:
            xobjs = page.get("/Resources", {}).get("/XObject", {})
            self.assertTrue(any(xobjs[k].get("/Subtype") == "/Image" for k in xobjs),
                            "tile page embeds no artwork")

    def test_each_tile_shows_its_own_window_of_the_artwork(self):
        # Every tile must place the artwork shifted by its own window
        # origin. A regression drew the image before the tile translate,
        # so all four sheets printed the same corner of the board.
        L = kit.build_layout(engine.load_rules(str(REPO / kit.RULES_FILE)))
        ax0, ay0, ax1, ay1 = L["art"]
        reader = PdfReader(self.out / "imperial-rivals-305ad-board-4xA4-ART.pdf")
        origins = []
        for page_no, page in zip(("1", "2", "3", "4"), reader.pages):
            x0, y0, _ = L["tiles"][page_no]
            ctm = image_matrix(page)
            self.assertAlmostEqual(ctm[0], (ax1 - ax0) * kit.mm, places=1)
            self.assertAlmostEqual(ctm[3], (ay1 - ay0) * kit.mm, places=1)
            self.assertAlmostEqual(ctm[4], (ax0 - x0) * kit.mm, places=1,
                                   msg=f"tile {page_no} x offset")
            self.assertAlmostEqual(ctm[5], (ay0 - y0) * kit.mm, places=1,
                                   msg=f"tile {page_no} y offset")
            origins.append((round(ctm[4], 1), round(ctm[5], 1)))
        self.assertEqual(len(set(origins)), 4, "two tiles show the same window")

    def test_succession_map_is_four_tiles_with_their_own_windows(self):
        S = kit.build_succession_layout(engine.load_rules(str(REPO / kit.RULES_FILE)))
        ax0, ay0, ax1, ay1 = S["art"]
        reader = PdfReader(self.out / "imperial-rivals-305ad-succession-map-ART.pdf")
        self.assertEqual(len(reader.pages), 4)
        for page_no, page in zip(("1", "2", "3", "4"), reader.pages):
            x0, y0, _ = S["tiles"][page_no]
            ctm = image_matrix(page)
            self.assertAlmostEqual(ctm[4], (ax0 - x0) * kit.mm, places=1)
            self.assertAlmostEqual(ctm[5], (ay0 - y0) * kit.mm, places=1)
            self.assertIn(f"SUCCESSION MAP - PAGE {page_no} OF 4", page.extract_text())

    def test_cards_page_places_six_card_images(self):
        reader = PdfReader(self.out / "imperial-rivals-305ad-cards-tokens-ART.pdf")
        self.assertEqual(len(reader.pages), 5)
        self.assertIn("FACTION CARDS", reader.pages[3].extract_text())
        self.assertIn("FACTION CARD BACKS", reader.pages[4].extract_text())
        for page in reader.pages:
            xobjs = page.get("/Resources", {}).get("/XObject", {})
            self.assertTrue(any(xobjs[k].get("/Subtype") == "/Image" for k in xobjs))


COLOR_ASSETS = ART_BUILD / "assets-color"


@unittest.skipUnless((COLOR_ASSETS / "palace-board.png").exists(),
                     "colour assets not rendered (run: node art/render.mjs --color)")
class ColorKit(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.out = Path(tempfile.mkdtemp(prefix="dioclet-color-"))
        rules = engine.load_rules(str(REPO / kit.RULES_FILE))
        cls.L = kit.build_layout(rules)
        cls.S = kit.build_succession_layout(rules)
        cls.board = cls.out / "board-COLOR.pdf"
        cls.succession = cls.out / "succession-COLOR.pdf"
        cls.cards = cls.out / "cards-COLOR.pdf"
        kit.art_board_pdf(str(cls.board), cls.L, kit.COLOR_ART_DIR, "full colour")
        kit.art_succession_pdf(str(cls.succession), cls.S, kit.COLOR_ART_DIR, "full colour")
        kit.art_cards_tokens_pdf(str(cls.cards), kit.COLOR_ART_DIR, "full colour")

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.out, ignore_errors=True)

    def test_every_grayscale_asset_has_a_colour_twin_of_the_same_size(self):
        from PIL import Image
        gray = sorted(p.name for p in (ART_BUILD / "assets").glob("*.png"))
        self.assertEqual(gray, sorted(p.name for p in COLOR_ASSETS.glob("*.png")))
        for name in gray:
            with Image.open(ART_BUILD / "assets" / name) as g, Image.open(COLOR_ASSETS / name) as c:
                self.assertEqual(g.size, c.size, name)

    def test_colour_assets_are_in_colour(self):
        from PIL import Image
        for name in ("palace-board.png", "succession-map.png", "card-back.png", "tokens-sheet.png"):
            with Image.open(COLOR_ASSETS / name) as im:
                hsv = im.convert("RGB").resize((200, 140)).convert("HSV")
                # A grayscale render has no saturated pixel at all.
                vivid = sum(1 for px in hsv.getdata() if px[1] > 60) / (200 * 140)
                self.assertGreater(vivid, 0.03, f"{name} looks grayscale")

    def test_boards_tile_like_the_art_kit(self):
        for path, layout in ((self.board, self.L), (self.succession, self.S)):
            reader = PdfReader(path)
            self.assertEqual(len(reader.pages), 4)
            ax0, ay0, _, _ = layout["art"]
            for page_no, page in zip(("1", "2", "3", "4"), reader.pages):
                x0, y0, _ = layout["tiles"][page_no]
                ctm = image_matrix(page)
                self.assertAlmostEqual(ctm[4], (ax0 - x0) * kit.mm, places=1)
                self.assertAlmostEqual(ctm[5], (ay0 - y0) * kit.mm, places=1)

    def test_cards_pdf_embeds_the_colour_images(self):
        reader = PdfReader(self.cards)
        self.assertEqual(len(reader.pages), 5)
        for page in reader.pages:
            xobjs = page["/Resources"]["/XObject"]
            spaces = {xobjs[k].get("/ColorSpace") for k in xobjs
                      if xobjs[k].get("/Subtype") == "/Image"}
            self.assertIn("/DeviceRGB", spaces)


if __name__ == "__main__":
    unittest.main()
