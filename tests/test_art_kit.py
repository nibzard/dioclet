"""Checks for the drawn art kit (art/ renderer and the ART PDFs).

The art is generated by JavaScript under art/, so Python can only pin
the contract around it:

- The geometry the renderer consumes is exported from the same layout
  functions the black-and-white kit uses, so both kits print the same
  board.
- When the rendered assets are present, the ART PDFs exist, carry the
  right page sizes and counts, and reuse the BW tiles' cut furniture.
- Nothing here runs Node: rendering is a separate build step
  (`node art/render.mjs`), and the tests skip cleanly without it.
"""

import json
import subprocess
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pypdf import PdfReader

import engine
from tools import make_a4_print_kit as kit

REPO = Path(__file__).resolve().parents[1]
ART_BUILD = REPO / "art" / "build"
PRINT = REPO / "print"
A4_SHORT_PT = 595.2756   # 210 mm
A4_LONG_PT = 841.8898    # 297 mm


class LayoutExport(unittest.TestCase):
    """The exported geometry matches the kit's own layout functions."""

    @classmethod
    def setUpClass(cls):
        cls.rules = engine.load_rules(str(REPO / kit.RULES_FILE))
        cls.export = json.loads((ART_BUILD / "layout.json").read_text())

    def test_export_exists_and_pins_the_rules_file(self):
        self.assertEqual(self.export["rules_file"], kit.RULES_FILE)
        self.assertEqual(self.export["rules_hash"], engine.rules_hash(self.rules))

    def test_palace_specials_match_the_kit_positions(self):
        L = kit.build_layout(self.rules)
        export = self.export["palace"]
        ax0, ay0, ax1, ay1 = L["art"]
        for name, cell in L["board"].gates.items():
            x, y = L["pos"](tuple(cell))
            self.assertAlmostEqual(export["gates"][name][0], x - ax0, places=3)
            self.assertAlmostEqual(export["gates"][name][1], ay1 - y, places=3)
        for (_cell, (x, y)), space in zip(L["spaces"], export["spaces"]):
            self.assertAlmostEqual(space["mm"][0], x - ax0, places=3)
            self.assertAlmostEqual(space["mm"][1], ay1 - y, places=3)

    def test_succession_factions_match_the_rules(self):
        S = kit.build_succession_layout(self.rules)
        export = self.export["succession"]
        for name, cell in self.rules["succession"]["factions"].items():
            x, y = S["pos"](tuple(cell))
            self.assertAlmostEqual(export["factions"][name][0], x, places=3)
            self.assertAlmostEqual(export["factions"][name][1], kit.PAGE_H - y, places=3)

    def test_cards_match_the_kit_card_list(self):
        items = self.export["cards"]["items"]
        self.assertEqual([i["name"] for i in items], [c[0] for c in kit.CARDS])
        self.assertEqual(self.export["cards"]["size_mm"], [kit.CARD_W, kit.CARD_H])


@unittest.skipUnless((ART_BUILD / "assets" / "palace-board.png").exists(),
                     "art assets not rendered (run: node art/render.mjs)")
class ArtKitPdfs(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        # Rebuild only the ART PDFs; the BW PDFs have their own tests.
        rules_arg = str(REPO / kit.RULES_FILE)
        script = (
            "import sys; sys.path.insert(0, '.'); sys.path.insert(0, 'tools');"
            "import make_a4_print_kit as kit;"
            f"rules = kit.engine.load_rules({rules_arg!r});"
            f"kit.art_board_pdf({str(PRINT / 'dioclet-board-4xA4-ART.pdf')!r}, kit.build_layout(rules));"
            f"kit.art_succession_pdf({str(PRINT / 'dioclet-succession-map-ART.pdf')!r});"
            f"kit.art_cards_tokens_pdf({str(PRINT / 'dioclet-cards-tokens-ART.pdf')!r})"
        )
        subprocess.run([sys.executable, "-c", script], cwd=str(REPO), check=True)

    def test_board_is_four_landscape_pages(self):
        reader = PdfReader(PRINT / "dioclet-board-4xA4-ART.pdf")
        self.assertEqual(len(reader.pages), 4)
        for page in reader.pages:
            self.assertAlmostEqual(float(page.mediabox.width), A4_LONG_PT, places=1)
            self.assertAlmostEqual(float(page.mediabox.height), A4_SHORT_PT, places=1)

    def test_every_art_board_page_carries_an_image(self):
        reader = PdfReader(PRINT / "dioclet-board-4xA4-ART.pdf")
        for page in reader.pages:
            xobjs = page.get("/Resources", {}).get("/XObject", {})
            self.assertTrue(any(xobjs[k].get("/Subtype") == "/Image" for k in xobjs),
                            "tile page embeds no artwork")

    def test_cards_page_places_six_card_images(self):
        reader = PdfReader(PRINT / "dioclet-cards-tokens-ART.pdf")
        self.assertEqual(len(reader.pages), 3)
        for page in reader.pages:
            xobjs = page.get("/Resources", {}).get("/XObject", {})
            self.assertTrue(any(xobjs[k].get("/Subtype") == "/Image" for k in xobjs))


if __name__ == "__main__":
    unittest.main()
